$ErrorActionPreference = 'Stop'
$projectDirectory = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$sourceDirectory = Join-Path $projectDirectory 'third-party\amane'
$sourcePath = Join-Path $sourceDirectory 'mapping_actor.xml'
$sourceInfo = Get-Content (Join-Path $sourceDirectory 'source.json') -Raw | ConvertFrom-Json
$settings = [System.Xml.XmlReaderSettings]::new()
$settings.DtdProcessing = [System.Xml.DtdProcessing]::Prohibit
$reader = [System.Xml.XmlReader]::Create($sourcePath, $settings)
$document = [System.Xml.XmlDocument]::new()
try { $document.Load($reader) } finally { $reader.Dispose() }

# These upstream entries describe groups, unknown people or invalid metadata.
# They must never become individual performers merely because they have a URL.
$nonPeople = @('女优', '别人', '错误', '素人', '素人(多人)', '素人妻', '素人娘',
  '素人(援交)', '素人(偷窃)', '素人(患者)', 'S级素人', 'SOD', '名誉毁损', '再生不能', '未知男优')
$records = [System.Collections.Generic.List[object]]::new()
$ignoredAliases = [System.Collections.Generic.List[string]]::new()
foreach ($row in $document.actor.a) {
  $aliases = @(@([string]$row.jp, [string]$row.zh_cn, [string]$row.zh_tw) +
    ([string]$row.keyword).Split(',') | ForEach-Object { $_.Trim() } |
    Where-Object { $_ -and $_ -notmatch '【.*?】' } | Select-Object -Unique)
  if ($nonPeople -contains [string]$row.zh_cn -or ([string]$row.keyword).Contains('【男優】')) {
    foreach ($alias in $aliases) { $ignoredAliases.Add($alias) }
    continue
  }
  $identity = [string]$row.href
  if ($identity) { $identity = $identity.TrimEnd('/') } else { $identity = $null }
  $records.Add([ordered]@{ id = $identity; name = [string]$row.zh_cn; aliases = [object[]]$aliases })
}
$data = [ordered]@{
  source = $sourceInfo.repository
  commit = $sourceInfo.commit
  sha256 = (Get-FileHash $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant()
  records = [object[]]$records.ToArray()
  ignoredAliases = [object[]]@($ignoredAliases | Select-Object -Unique)
}
$json = ConvertTo-Json -InputObject $data -Depth 8 -Compress
$output = '// Generated by scripts/build-actress-data.ps1 from Amane. See THIRD_PARTY_NOTICES.md.' + "`n" +
  'globalThis.MissavActressData = ' + $json + ";`n"
[System.IO.File]::WriteAllText((Join-Path $projectDirectory 'actress-data.js'), $output, [System.Text.UTF8Encoding]::new($false))
Write-Output "Built $($records.Count) performer mapping records."
